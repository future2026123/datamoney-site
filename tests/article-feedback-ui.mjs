import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {DatabaseSync} from 'node:sqlite';
import worker, {ArticleEngagement} from '../workers/article-engagement.js';

const require = createRequire(new URL('../workers/package.json', import.meta.url));
const {JSDOM} = require('jsdom');
const html = await readFile(new URL('../blog/why-we-want-financial-freedom-ep01/index.html', import.meta.url), 'utf8');
const script = await readFile(new URL('../blog/article-actions.js', import.meta.url), 'utf8');
const db = new DatabaseSync(':memory:');
const storage = {sql:{exec(sql, ...args) { const rows=db.prepare(sql).all(...args); return {toArray:() => rows, one:() => rows[0]}; }}, setAlarm:async () => {}};
const object = new ArticleEngagement({storage});
const env = {DM_COMMENT_ADMIN_KEY:'test-key', ARTICLE_ENGAGEMENT:{idFromName:() => 'test', get:() => object}};
const dom = new JSDOM(html, {url:'https://datamoney.kr/blog/why-we-want-financial-freedom-ep01/', runScripts:'outside-only'});
let cookie = '';
let failNext = false;
dom.window.fetch = async (input, options={}) => {
  const url = new URL(input, dom.window.location.href);
  if (url.pathname.endsWith('/feedback') && failNext) { failNext=false; return new Response('{}', {status:503}); }
  const headers = new Headers(options.headers || {});
  headers.set('origin', url.origin); headers.set('cf-connecting-ip','192.0.2.10');
  if (cookie) headers.set('cookie', cookie);
  const result = await worker.fetch(new Request(url, {...options, headers}), env);
  if (result.headers.get('set-cookie')) cookie = result.headers.get('set-cookie').split(';')[0];
  return result;
};
dom.window.eval(script);
const tick = () => new Promise(resolve => setTimeout(resolve, 30));
await tick();
const document = dom.window.document;
const section = document.querySelector('.dm-feedback');
assert.ok(section);
assert.equal(section.nextElementSibling.className, 'dm-references', 'feedback follows the article and precedes references');
assert.equal(section.querySelector('form').hidden, true, 'the optional form is hidden before an evaluation');
const helpful = section.querySelector('[data-feedback-choice=helpful]');
failNext = true; helpful.click(); await tick();
assert.match(section.querySelector('[role=status]').textContent, /보내지 못했어요/);
assert.equal(helpful.disabled, false, 'a failed submission can be retried');
helpful.click(); await tick();
assert.equal(helpful.getAttribute('aria-pressed'), 'true');
assert.equal(section.querySelector('form').hidden, false);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM article_feedback').get().n, 1, 'a single choice is saved immediately');
const field = section.querySelector('textarea'); field.value = '예시가 더 있으면 좋겠어요.';
section.querySelector('form').dispatchEvent(new dom.window.Event('submit', {bubbles:true, cancelable:true}));
await tick();
assert.equal(db.prepare('SELECT body FROM article_feedback').get().body, field.value, 'optional text updates the same response');
assert.match(section.querySelector('[role=status]').textContent, /의견을 보내주셔서/);
section.querySelector('[data-feedback-choice=difficult]').click(); await tick();
assert.equal(db.prepare('SELECT choice, body FROM article_feedback').get().choice, 'difficult');
assert.equal(db.prepare('SELECT body FROM article_feedback').get().body, field.value, 'editing a choice retains the note');
dom.window.close();
console.log('Article feedback UI: immediate voting, retry, optional note and editing passed');
