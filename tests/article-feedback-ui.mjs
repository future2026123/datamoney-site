import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {DatabaseSync} from 'node:sqlite';
import worker, {ArticleEngagement} from '../workers/article-engagement.js';

const require = createRequire(new URL('../workers/package.json', import.meta.url));
const {JSDOM} = require('jsdom');
const html = await readFile(new URL('../blog/why-we-want-financial-freedom-ep01/index.html', import.meta.url), 'utf8');
const script = await readFile(new URL('../blog/article-actions.js', import.meta.url), 'utf8');
const db = new DatabaseSync(':memory:');
const storage = {sql:{exec(sql, ...args) { const rows=db.prepare(sql).all(...args); return {toArray:() => rows, one:() => rows[0]}; }}, setAlarm:async () => {}};
const object = new ArticleEngagement({storage});
const env = {DM_COMMENT_ADMIN_KEY:'test-key', ARTICLE_ENGAGEMENT:{idFromName:() => 'test', get:() => object}};
const dom = new JSDOM(html, {url:'https://datamoney.kr/blog/why-we-want-financial-freedom-ep01/', runScripts:'outside-only'});
let cookie = '';
let failNext = false;
dom.window.fetch = async (input, options={}) => {
  const url = new URL(input, dom.window.location.href);
  if (url.pathname.endsWith('/feedback') && failNext) { failNext=false; return new Response('{}', {status:503}); }
  const headers = new Headers(options.headers || {});
  headers.set('origin', url.origin); headers.set('cf-connecting-ip','192.0.2.10');
  if (cookie) headers.set('cookie', cookie);
  const result = await worker.fetch(new Request(url, {...options, headers}), env);
  if (result.headers.get('set-cookie')) cookie = result.headers.get('set-cookie').split(';')[0];
  return result;
};
dom.window.eval(script);
const tick = () => new Promise(resolve => setTimeout(resolve, 30));
await tick();
const document = dom.window.document;
assert.equal(document.querySelector('.dm-feedback'), null, 'the old feedback panel is absent');
const like = document.querySelector('[data-end-reaction]');
const dislike = document.querySelector('[data-end-dislike]');
assert.ok(like && dislike);
assert.equal(like.nextElementSibling, dislike);
assert.equal(dislike.textContent.trim(), '👎싫어요');
dislike.click(); await tick();
assert.equal(dislike.getAttribute('aria-pressed'), 'true');
assert.equal(like.getAttribute('aria-pressed'), 'false');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM dislikes').get().n, 1);
const summary = await (await dom.window.fetch('/api/article-engagement/why-we-want-financial-freedom-ep01')).json();
assert.equal(summary.disliked, true);
assert.equal('dislikes' in summary, false, 'public response never exposes dislike totals');
const admin = await worker.fetch(new Request('https://datamoney.kr/api/article-engagement/_admin/feedback', {headers:{authorization:'Bearer test-key'}}), env);
assert.equal((await admin.json()).dislikes[0].count, 1, 'administrator sees the count');
like.click(); await tick();
assert.equal(dislike.getAttribute('aria-pressed'), 'false');
assert.equal(like.getAttribute('aria-pressed'), 'true');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM dislikes').get().n, 0, 'switching to like removes dislike');
dislike.click(); await tick();
assert.equal(like.getAttribute('aria-pressed'), 'false');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM reactions').get().n, 0, 'switching to dislike removes like');
dislike.click(); await tick();
assert.equal(dislike.getAttribute('aria-pressed'), 'false', 'clicking again removes dislike');
dom.window.close();
console.log('Article reactions: private dislike count, switching and cancellation passed');
