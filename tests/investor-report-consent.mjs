import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';

const require=createRequire(new URL('../workers/package.json',import.meta.url));
const {JSDOM}=require('jsdom');
const html=await readFile(new URL('../tools/investor-type/index.html',import.meta.url),'utf8');
const script=await readFile(new URL('../tools/investor-type/email.js',import.meta.url),'utf8');
const dom=new JSDOM(html,{url:'https://datamoney.kr/tools/investor-type/',runScripts:'outside-only'});
const w=dom.window, d=w.document, calls=[];
w.fetch=async (url,options)=>{calls.push({url,body:JSON.parse(options.body)});return {ok:true};};
w.eval(script);
w.dmOnInvestorResult({typeCode:0,anxiety:0,reaction:0,tipCode:0});
assert.equal(calls.length,0,'receiving the basic result never requests an email');
assert.match(d.querySelector('.email-lead').textContent,/이메일 없이 바로 볼 수/);
assert.ok(d.querySelector('.result-details'));
d.getElementById('result-email').value='reader@example.com';
const form=d.getElementById('result-email-form');
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(calls.length,0,'a report cannot be requested without consent');
d.getElementById('result-email-consent').checked=true;
form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(calls.length,1);
assert.equal(calls[0].body.consent,true);
assert.equal(calls[0].body.testNews,false);
assert.equal(calls[0].body.monthlyReport,false);
dom.window.close();
console.log('Basic result is free to view; report request requires consent');
