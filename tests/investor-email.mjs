import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {DatabaseSync} from 'node:sqlite';
const source=await readFile(new URL('../workers/article-engagement.js',import.meta.url));
const {default:worker,ArticleEngagement}=await import('data:text/javascript;base64,'+source.toString('base64'));
const db=new DatabaseSync(':memory:');
const state={storage:{sql:{exec(sql,...args){const rows=db.prepare(sql).all(...args);return {toArray:()=>rows,one:()=>rows[0]};}},setAlarm:async()=>{}}};
const env={DM_COMMENT_ADMIN_KEY:'admin-secret',RESEND_API_KEY:'test-key'};
const obj=new ArticleEngagement(state,env);
env.ARTICLE_ENGAGEMENT={idFromName:()=>'',get:()=>obj};
const base='https://datamoney.kr/api/article-engagement';
const originalFetch=globalThis.fetch;
let sent=[],sendOK=true;
globalThis.fetch=async (url,options)=>{
  assert.equal(url,'https://api.resend.com/emails');
  assert.equal(options.headers.authorization,'Bearer test-key');
  sent.push(JSON.parse(options.body));
  return {ok:sendOK};
};
async function call(path,{method='POST',body={},headers={}}={}){
  const response=await worker.fetch(new Request(base+path,{method,headers:{origin:'https://datamoney.kr','cf-connecting-ip':'192.0.2.1',...headers},...(method==='GET'?{}:{body:JSON.stringify(body)})}),env);
  return {status:response.status,data:await response.json()};
}
const input={email:'reader@example.com',typeCode:5,anxiety:2,reaction:1,tipCode:2,consent:true,testNews:true,monthlyReport:false};
assert.equal((await call('/_email/request',{body:{...input,consent:false}})).status,400);
assert.equal((await call('/_email/request',{body:input,headers:{origin:'https://elsewhere.example'}})).status,403);
assert.equal((await call('/_email/request',{body:{...input,email:'bad\n@example.com'}})).status,400);
assert.equal((await call('/_email/request',{body:input})).status,200);
assert.equal(sent.length,1);
assert.deepEqual(sent[0].to,['reader@example.com']);
const token=sent[0].text.match(/\/account\/result\/#([a-f0-9]{64})/)[1];
const row=db.prepare('SELECT * FROM email_results').get();
assert.notEqual(row.token_hash,token,'the emailed bearer token must not be stored in plaintext');
assert.equal(row.confirmed_at,null);
assert.equal((await call('/_admin/email-subscribers',{method:'GET',headers:{'x-article-admin':'authorized'}})).status,401);
const admin=()=>call('/_admin/email-subscribers',{method:'GET',headers:{authorization:'Bearer admin-secret'}});
assert.equal((await admin()).data.items.length,0,'unconfirmed email must not become a subscriber');
assert.equal((await call('/_email/preferences',{body:{token,testNews:false,monthlyReport:false}})).status,403);
const opened=await call('/_email/open',{body:{token}});
assert.equal(opened.status,200);
assert.equal(opened.data.result.typeCode,5);
assert.deepEqual(opened.data.subscriptions,{testNews:true,monthlyReport:false});
assert.equal((await admin()).data.items[0].email,'reader@example.com');
assert.equal((await call('/_email/preferences',{body:{token,testNews:false,monthlyReport:false}})).status,200);
assert.equal((await admin()).data.items.length,0,'withdrawal removes the subscriber from the marketing list');
assert.equal((await call('/_email/delete',{body:{token}})).status,200);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM email_results').get().n,0);
assert.equal((await call('/_email/open',{body:{token}})).status,404);
sendOK=false;
assert.equal((await call('/_email/request',{body:{...input,email:'other@example.com'}})).status,502);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM email_results').get().n,0,'failed sends must not retain a pending result');
globalThis.fetch=originalFetch;
console.log('Result emails, separate confirmed subscriptions, withdrawal and deletion: passed');
